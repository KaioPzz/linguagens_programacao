public class Main {
    static void entrar(){
        System.out.println("Voce entrou na sala.");
    }

    static void acionar(){
        System.out.println("Voce acionou a alavanca.");
    }
    static void sair(){
        System.out.println("Voce saiu da sala.");
    }
    public static void main(String[] args){
        entrar();
        acionar();
        sair();
    }
}